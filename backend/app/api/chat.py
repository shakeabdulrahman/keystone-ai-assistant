"""POST /v1/chat: send a message and stream the assistant's reply as Server-Sent Events."""

import contextlib
from collections.abc import AsyncIterator
from typing import Annotated
from uuid import UUID

from fastapi import APIRouter, Depends
from pydantic import BaseModel, Field, field_validator

from app.ai.events import SseEncoder
from app.api.deps import CurrentUser, get_chat_service, get_settings_dep
from app.api.streaming import ClosingStreamingResponse, with_heartbeat
from app.core.config import Settings
from app.services.chat_service import ChatService, ChatTurn

router = APIRouter(prefix="/v1", tags=["chat"])


class ChatRequest(BaseModel):
    conversation_id: UUID | None = None
    client_message_id: UUID = Field(description="Generated by the app; makes retries idempotent")
    content: str = Field(min_length=1, max_length=4000)

    @field_validator("content")
    @classmethod
    def not_blank(cls, value: str) -> str:
        stripped = value.strip()
        if not stripped:
            raise ValueError("must not be blank")
        return stripped


@router.post(
    "/chat",
    response_class=ClosingStreamingResponse,
    responses={200: {"content": {"text/event-stream": {}}, "description": "SSE stream of events"}},
)
async def chat(
    body: ChatRequest,
    user: CurrentUser,
    service: Annotated[ChatService, Depends(get_chat_service)],
    settings: Annotated[Settings, Depends(get_settings_dep)],
) -> ClosingStreamingResponse:
    turn = await service.start_turn(
        user=user,
        conversation_id=body.conversation_id,
        client_message_id=str(body.client_message_id),
        content=body.content,
    )
    return ClosingStreamingResponse(
        with_heartbeat(_encode(service, turn), settings.sse_heartbeat_s),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",  # tell reverse proxies not to buffer the stream
        },
    )


async def _encode(service: ChatService, turn: ChatTurn) -> AsyncIterator[str]:
    encoder = SseEncoder()
    # aclosing propagates a disconnect down to the chat service (see ChatService.stream_turn).
    async with contextlib.aclosing(service.stream_turn(turn)) as events:
        async for event in events:
            yield encoder.encode(event)
